# Create a copy for feature engineering
df = silver_df.copy()

# 1. Lag Features (Price)
print("📊 Creating lag features...")
for lag in range(1, 8):
    df[f'Close_Lag_{lag}'] = df['Close'].shift(lag)
    df[f'Return_Lag_{lag}'] = df['Returns'].shift(lag)

# 2. Rolling Statistics
print("📊 Creating rolling statistics...")
for window in [5, 10, 20, 30, 60]:
    df[f'Rolling_Mean_{window}'] = df['Close'].rolling(window=window).mean()
    df[f'Rolling_Std_{window}'] = df['Close'].rolling(window=window).std()
    df[f'Rolling_Min_{window}'] = df['Close'].rolling(window=window).min()
    df[f'Rolling_Max_{window}'] = df['Close'].rolling(window=window).max()

# 3. Momentum Features
print("📊 Creating momentum features...")
df['Momentum_5'] = df['Close'] / df['Close'].shift(5) - 1
df['Momentum_10'] = df['Close'] / df['Close'].shift(10) - 1
df['Momentum_20'] = df['Close'] / df['Close'].shift(20) - 1

# 4. Price Position Features
df['Price_Position_20'] = (df['Close'] - df['Rolling_Min_20']) / (df['Rolling_Max_20'] - df['Rolling_Min_20'] + 0.001)
df['Distance_SMA20'] = (df['Close'] - df['SMA_20']) / df['SMA_20']
df['Distance_SMA50'] = (df['Close'] - df['SMA_50']) / df['SMA_50']

# 5. Date Features
print("📊 Creating date features...")
df['Year'] = df['Date'].dt.year
df['Month'] = df['Date'].dt.month
df['DayOfWeek'] = df['Date'].dt.dayofweek
df['DayOfMonth'] = df['Date'].dt.day
df['Quarter'] = df['Date'].dt.quarter
df['WeekOfYear'] = df['Date'].dt.isocalendar().week.astype(int)

# 6. Cyclical encoding for date features
df['Month_Sin'] = np.sin(2 * np.pi * df['Month'] / 12)
df['Month_Cos'] = np.cos(2 * np.pi * df['Month'] / 12)
df['DayOfWeek_Sin'] = np.sin(2 * np.pi * df['DayOfWeek'] / 5)
df['DayOfWeek_Cos'] = np.cos(2 * np.pi * df['DayOfWeek'] / 5)

# 7. Volatility Features
df['High_Low_Pct'] = (df['High'] - df['Low']) / df['Low']
df['Open_Close_Pct'] = (df['Close'] - df['Open']) / df['Open']


    # Simple random walk with drift for future projections
    drift = 0.0003  # Slight positive drift based on trend
    shock = np.random.normal(0, historical_vol)
    base_forecast = base_forecast * (1 + drift + shock)
    ensemble_forecasts.append(base_forecast)

